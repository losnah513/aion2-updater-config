create or replace function private.kinojo_banner_bigint_array_v407(
  p_value jsonb,
  p_max integer default 99
) returns bigint[]
language plpgsql
immutable
security definer
set search_path=pg_catalog,public,private
as $function$
declare
  v_result bigint[]:='{}'::bigint[];
  v_raw text;
  v_id bigint;
begin
  if p_value is null then return v_result; end if;
  if pg_catalog.jsonb_typeof(p_value)<>'array' or pg_catalog.jsonb_array_length(p_value)>p_max then
    raise exception using errcode='P0001',message='BANNER_ARRAY_INVALID';
  end if;
  for v_raw in select value from pg_catalog.jsonb_array_elements_text(p_value)
  loop
    begin v_id:=v_raw::bigint; exception when others then
      raise exception using errcode='P0001',message='BANNER_ARRAY_INVALID';
    end;
    if v_id<=0 or v_id=any(v_result) then
      raise exception using errcode='P0001',message='BANNER_ARRAY_INVALID';
    end if;
    v_result:=pg_catalog.array_append(v_result,v_id);
  end loop;
  return v_result;
end
$function$;

