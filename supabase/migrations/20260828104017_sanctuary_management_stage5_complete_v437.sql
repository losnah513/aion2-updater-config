-- Sanctuary management Stage 5 / DB 437
-- Server-owned recruitment alerts, Wednesday-first calendar, scoped schedule
-- operations and archive impact preview. Historical roster/audit rows are kept.

create table if not exists private.sanctuary_management_schedule_versions_v437 (
  schedule_version_id bigint generated by default as identity primary key,
  schedule_id bigint not null references private.sanctuary_management_schedule_rules_v412(schedule_id) on delete cascade,
  team_id bigint not null references private.sanctuary_management_teams_v412(team_id) on delete cascade,
  effective_from date not null,
  effective_to date,
  schedule_kind text not null check (schedule_kind in ('ONCE','WEEKLY')),
  starts_on date not null,
  weekdays smallint[] not null default '{}',
  starts_at time not null,
  duration_minutes integer not null default 30 check (duration_minutes between 30 and 720 and duration_minutes % 30 = 0),
  timezone_name text not null default 'Asia/Seoul',
  status text not null default 'ACTIVE' check (status in ('ACTIVE','STOPPED')),
  revision bigint not null default 1,
  created_by_member_id bigint references public.member_codes(id) on delete restrict,
  created_at timestamptz not null default clock_timestamp(),
  check (effective_to is null or effective_to >= effective_from),
  check ((schedule_kind='ONCE' and cardinality(weekdays)=0) or (schedule_kind='WEEKLY' and cardinality(weekdays) between 1 and 7)),
  unique(schedule_id,effective_from)
);

create index if not exists sanctuary_management_schedule_versions_v437_team_range_idx
  on private.sanctuary_management_schedule_versions_v437(team_id,effective_from,effective_to);
alter table private.sanctuary_management_schedule_versions_v437 enable row level security;
revoke all on private.sanctuary_management_schedule_versions_v437 from public, anon, authenticated;

alter table private.sanctuary_management_schedule_exceptions_v412
  add column if not exists moved_duration_minutes integer;
update private.sanctuary_management_schedule_exceptions_v412 e
   set moved_duration_minutes=r.duration_minutes
  from private.sanctuary_management_schedule_rules_v412 r
 where e.schedule_id=r.schedule_id and e.exception_type='MOVE' and e.moved_duration_minutes is null;
alter table private.sanctuary_management_schedule_exceptions_v412
  drop constraint if exists sanctuary_management_schedule_exceptions_v412_check;
alter table private.sanctuary_management_schedule_exceptions_v412
  add constraint sanctuary_management_schedule_exceptions_v437_check check (
    (exception_type='CANCEL' and moved_to_date is null and moved_to_time is null and moved_duration_minutes is null)
    or
    (exception_type='MOVE' and moved_to_date is not null and moved_to_time is not null
      and moved_duration_minutes between 30 and 720 and moved_duration_minutes % 30 = 0)
  );

insert into private.sanctuary_management_schedule_versions_v437(
  schedule_id,team_id,effective_from,schedule_kind,starts_on,weekdays,starts_at,
  duration_minutes,timezone_name,status,revision,created_by_member_id
)
select r.schedule_id,r.team_id,r.starts_on,r.schedule_kind,r.starts_on,r.weekdays,r.starts_at,
       r.duration_minutes,r.timezone_name,r.status,r.revision,t.creator_member_id
  from private.sanctuary_management_schedule_rules_v412 r
  join private.sanctuary_management_teams_v412 t on t.team_id=r.team_id
 where not exists(
   select 1 from private.sanctuary_management_schedule_versions_v437 v where v.schedule_id=r.schedule_id
 );

create or replace function private.kinojo_sm_schedule_version_sync_v437()
returns trigger
language plpgsql
security definer
set search_path='pg_catalog','public','private'
as $$
declare v_actor_id bigint;
begin
  if coalesce(current_setting('kinojo.schedule_version_guard',true),'')='1' then return new; end if;
  select creator_member_id into v_actor_id from private.sanctuary_management_teams_v412 where team_id=new.team_id;
  if tg_op='UPDATE' then
    delete from private.sanctuary_management_schedule_versions_v437 where schedule_id=new.schedule_id;
  end if;
  insert into private.sanctuary_management_schedule_versions_v437(
    schedule_id,team_id,effective_from,schedule_kind,starts_on,weekdays,starts_at,
    duration_minutes,timezone_name,status,revision,created_by_member_id
  ) values(
    new.schedule_id,new.team_id,new.starts_on,new.schedule_kind,new.starts_on,new.weekdays,new.starts_at,
    new.duration_minutes,new.timezone_name,new.status,new.revision,v_actor_id
  );
  return new;
end;
$$;

drop trigger if exists sanctuary_management_schedule_version_sync_v437 on private.sanctuary_management_schedule_rules_v412;
create trigger sanctuary_management_schedule_version_sync_v437
after insert or update of schedule_kind,starts_on,weekdays,starts_at,duration_minutes,timezone_name,status
on private.sanctuary_management_schedule_rules_v412
for each row execute function private.kinojo_sm_schedule_version_sync_v437();

create or replace function private.kinojo_sm_rule_occurrences_v437(p_schedule_id bigint,p_from date,p_to date)
returns table(occurrence_date date,start_at timestamptz,end_at timestamptz,source_scope text)
language sql
stable security definer
set search_path='pg_catalog','private'
as $$
  with versions as (
    select * from private.sanctuary_management_schedule_versions_v437
     where schedule_id=p_schedule_id and status='ACTIVE'
       and effective_from<=p_to and coalesce(effective_to,'infinity'::date)>=p_from
  ), generated as (
    select d::date occurrence_date,v.*
      from versions v
      cross join lateral generate_series(
        greatest(p_from,v.effective_from,v.starts_on),
        least(p_to,coalesce(v.effective_to,p_to)),interval '1 day'
      ) d
     where (v.schedule_kind='ONCE' and d::date=v.starts_on)
        or (v.schedule_kind='WEEKLY' and extract(isodow from d)::smallint=any(v.weekdays))
  ), originals as (
    select g.occurrence_date,
           ((g.occurrence_date+g.starts_at) at time zone g.timezone_name) start_at,
           (((g.occurrence_date+g.starts_at)+make_interval(mins=>g.duration_minutes)) at time zone g.timezone_name) end_at,
           'RULE'::text source_scope
      from generated g
     where not exists(select 1 from private.sanctuary_management_schedule_exceptions_v412 e
       where e.schedule_id=g.schedule_id and e.occurrence_date=g.occurrence_date)
  ), moved as (
    select e.moved_to_date,
           ((e.moved_to_date+e.moved_to_time) at time zone v.timezone_name),
           (((e.moved_to_date+e.moved_to_time)+make_interval(mins=>e.moved_duration_minutes)) at time zone v.timezone_name),
           'OCCURRENCE'::text
      from private.sanctuary_management_schedule_exceptions_v412 e
      join versions v on v.schedule_id=e.schedule_id
       and e.occurrence_date between v.effective_from and coalesce(v.effective_to,'infinity'::date)
     where e.schedule_id=p_schedule_id and e.exception_type='MOVE'
       and e.moved_to_date between p_from and p_to
  )
  select * from originals union all select * from moved;
$$;

create or replace function private.kinojo_sm_team_conflicts_v437(p_team_id bigint,p_from date,p_to date)
returns jsonb
language sql
stable security definer
set search_path='pg_catalog','public','private'
as $$
  select coalesce(jsonb_agg(distinct jsonb_build_object(
    'teamId',other_team.team_id,'teamTitle',other_team.title,'characterName',cm.character_name,
    'message','['||case mine.character_relation when 'MAIN' then '본캐' when 'ALT' then '부캐' else '게스트' end||'] '
      ||cm.character_name||' 캐릭터가 참여하고 있는 '||other_team.title||' 일정과 충돌합니다.'
  )),'[]'::jsonb)
  from private.sanctuary_management_teams_v412 candidate_team
  join private.sanctuary_management_schedule_rules_v412 candidate_rule on candidate_rule.team_id=candidate_team.team_id
  join private.sanctuary_management_slots_v412 mine on mine.team_id=candidate_team.team_id and mine.character_id is not null
  join public.character_master cm on cm.id=mine.character_id
  join private.sanctuary_management_slots_v412 other_slot
    on other_slot.team_id<>candidate_team.team_id and other_slot.character_id is not null
   and ((mine.owner_member_id is not null and other_slot.owner_member_id=mine.owner_member_id)
     or (mine.owner_root_character_id is not null and other_slot.owner_root_character_id=mine.owner_root_character_id))
  join private.sanctuary_management_teams_v412 other_team on other_team.team_id=other_slot.team_id and other_team.status in ('ACTIVE','FULL')
  join private.sanctuary_management_schedule_rules_v412 other_rule on other_rule.team_id=other_team.team_id
  cross join lateral private.kinojo_sm_rule_occurrences_v437(candidate_rule.schedule_id,p_from,p_to) candidate_occurrence
  cross join lateral private.kinojo_sm_rule_occurrences_v437(other_rule.schedule_id,p_from,p_to) other_occurrence
  where candidate_team.team_id=p_team_id
    and candidate_team.status in ('ACTIVE','FULL')
    and tstzrange(candidate_occurrence.start_at,candidate_occurrence.end_at,'[)')
        && tstzrange(other_occurrence.start_at,other_occurrence.end_at,'[)');
$$;

