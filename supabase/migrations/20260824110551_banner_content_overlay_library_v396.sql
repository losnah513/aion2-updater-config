create or replace function private.kinojo_banner_content_layer_normalize_v396(
  p_value jsonb
) returns jsonb
language plpgsql
immutable
set search_path = pg_catalog, private
as $function$
declare
  v_value jsonb := coalesce(p_value,'{}'::jsonb);
  v_type text := 'TEXT';
  v_enabled boolean := true;
  v_layer_position text := 'FRONT';
  v_vertical text := 'BOTTOM';
  v_horizontal text := 'CENTER';
  v_opacity integer := 100;
  v_size integer := 24;
  v_rotation integer := 0;
  v_asset_id bigint;
  v_emoji text := '';
  v_text_input jsonb;
  v_text jsonb;
begin
  if jsonb_typeof(v_value)<>'object' then
    raise exception using errcode='P0001',message='BANNER_CONTENT_LAYER_INVALID';
  end if;
  if exists (
    select 1 from jsonb_object_keys(v_value) key_name
    where key_name not in (
      'type','enabled','layerPosition','verticalPosition','horizontalPosition',
      'opacity','sizePercent','rotationDeg','overlayAssetId','emoji',
      'text','fontFamily','fontSizePx','textColor','backgroundColor',
      'backgroundOpacity','heightPercent','widthMode'
    )
  ) then
    raise exception using errcode='P0001',message='BANNER_CONTENT_LAYER_FIELD_INVALID';
  end if;

  v_type := upper(btrim(coalesce(nullif(v_value->>'type',''),'TEXT')));
  if v_type not in ('TEXT','EMOJI','EMOTICON','STICKER','BADGE') then
    raise exception using errcode='P0001',message='BANNER_CONTENT_LAYER_TYPE_INVALID';
  end if;
  if v_value ? 'enabled' then
    if jsonb_typeof(v_value->'enabled')<>'boolean' then
      raise exception using errcode='P0001',message='BANNER_CONTENT_LAYER_ENABLED_INVALID';
    end if;
    v_enabled := (v_value->>'enabled')::boolean;
  end if;
  v_layer_position := upper(btrim(coalesce(nullif(v_value->>'layerPosition',''),'FRONT')));
  if v_layer_position not in ('FRONT','BACK') then
    raise exception using errcode='P0001',message='BANNER_CONTENT_LAYER_POSITION_INVALID';
  end if;
  v_vertical := upper(btrim(coalesce(nullif(v_value->>'verticalPosition',''),'BOTTOM')));
  if v_vertical not in ('TOP','MIDDLE','BOTTOM') then
    raise exception using errcode='P0001',message='BANNER_CONTENT_LAYER_VERTICAL_INVALID';
  end if;
  v_horizontal := upper(btrim(coalesce(nullif(v_value->>'horizontalPosition',''),'CENTER')));
  if v_horizontal not in ('LEFT','CENTER','RIGHT') then
    raise exception using errcode='P0001',message='BANNER_CONTENT_LAYER_HORIZONTAL_INVALID';
  end if;

  begin
    v_opacity := coalesce((v_value->>'opacity')::integer,100);
    v_size := coalesce((v_value->>'sizePercent')::integer,24);
    v_rotation := coalesce((v_value->>'rotationDeg')::integer,0);
  exception when others then
    raise exception using errcode='P0001',message='BANNER_CONTENT_LAYER_GEOMETRY_INVALID';
  end;
  if v_opacity not between 0 and 100 or v_size not between 5 and 60
     or v_rotation not between -180 and 180 then
    raise exception using errcode='P0001',message='BANNER_CONTENT_LAYER_GEOMETRY_INVALID';
  end if;

  if v_type='TEXT' then
    v_text_input := v_value - 'type' - 'layerPosition' - 'horizontalPosition'
      - 'opacity' - 'sizePercent' - 'rotationDeg' - 'overlayAssetId' - 'emoji';
    -- Drafts may preserve an unfinished enabled text layer. The legacy mirror
    -- remains disabled until the text is complete, while v396 keeps intent.
    if v_enabled and char_length(btrim(coalesce(v_value->>'text','')))=0 then
      v_text_input := v_text_input || jsonb_build_object('enabled',false);
    end if;
    v_text := private.kinojo_banner_text_overlay_normalize_v394(v_text_input);
    return v_text || jsonb_build_object(
      'type','TEXT','enabled',v_enabled,'layerPosition',v_layer_position,
      'horizontalPosition','CENTER','opacity',v_opacity,
      'sizePercent',v_size,'rotationDeg',v_rotation
    );
  end if;

  if v_type='EMOJI' then
    v_emoji := coalesce(v_value->>'emoji','');
    if char_length(v_emoji)>12 then
      raise exception using errcode='P0001',message='BANNER_CONTENT_EMOJI_INVALID';
    end if;
    return jsonb_build_object(
      'type','EMOJI','enabled',v_enabled,'emoji',v_emoji,
      'layerPosition',v_layer_position,'verticalPosition',v_vertical,
      'horizontalPosition',v_horizontal,'opacity',v_opacity,
      'sizePercent',v_size,'rotationDeg',v_rotation
    );
  end if;

  if v_value ? 'overlayAssetId' and v_value->'overlayAssetId'<>'null'::jsonb then
    begin
      v_asset_id := (v_value->>'overlayAssetId')::bigint;
    exception when others then
      raise exception using errcode='P0001',message='BANNER_CONTENT_ASSET_ID_INVALID';
    end;
    if v_asset_id<1 then
      raise exception using errcode='P0001',message='BANNER_CONTENT_ASSET_ID_INVALID';
    end if;
  end if;
  return jsonb_build_object(
    'type',v_type,'enabled',v_enabled,'overlayAssetId',v_asset_id,
    'layerPosition',v_layer_position,'verticalPosition',v_vertical,
    'horizontalPosition',v_horizontal,'opacity',v_opacity,
    'sizePercent',v_size,'rotationDeg',v_rotation
  );
end;
$function$;

create or replace function private.kinojo_banner_content_overlays_normalize_v396(
  p_value jsonb
) returns jsonb
language plpgsql
immutable
set search_path = pg_catalog, private
as $function$
declare
  v_value jsonb := case when p_value is null or p_value='null'::jsonb
    then '[]'::jsonb else p_value end;
  v_result jsonb := '[]'::jsonb;
  v_item jsonb;
  v_normalized jsonb;
  v_text_count integer := 0;
  v_decor_count integer := 0;
begin
  if jsonb_typeof(v_value)<>'array' or jsonb_array_length(v_value)>6 then
    raise exception using errcode='P0001',message='BANNER_CONTENT_LAYERS_INVALID';
  end if;
  for v_item in select value from jsonb_array_elements(v_value)
  loop
    v_normalized := private.kinojo_banner_content_layer_normalize_v396(v_item);
    if v_normalized->>'type'='TEXT' then
      v_text_count := v_text_count+1;
    else
      v_decor_count := v_decor_count+1;
    end if;
    if v_text_count>3 or v_decor_count>3 then
      raise exception using errcode='P0001',message='BANNER_CONTENT_LAYER_LIMIT';
    end if;
    v_result := v_result || jsonb_build_array(v_normalized);
  end loop;
  return v_result;
end;
$function$;

