create or replace function public.kinojo_banner_composite_register_v396(
  p_session_token text,
  p_event_group_id uuid,
  p_asset_id bigint,
  p_object_path text,
  p_mime_type text,
  p_size_bytes bigint,
  p_width integer,
  p_height integer
) returns jsonb
language plpgsql
security definer
set search_path = pg_catalog, public, private
as $function$
declare
  v_gate jsonb;
  v_kind text;
  v_hash text;
  v_hash_count integer;
  v_updated integer;
begin
  v_gate := private.kinojo_banner_require_master_v384(p_session_token);
  if coalesce((v_gate->>'ok')::boolean,false) is not true then return v_gate; end if;
  if p_event_group_id is null or coalesce(p_asset_id,0)<1 then
    return jsonb_build_object('ok',false,'code','BANNER_COMPOSITE_TARGET_INVALID');
  end if;

  select min(c.campaign_type),count(distinct md5(
    private.kinojo_banner_content_overlays_normalize_v396(i.content_overlays)::text
  )),min(md5(
    private.kinojo_banner_content_overlays_normalize_v396(i.content_overlays)::text
  )) into v_kind,v_hash_count,v_hash
  from public.kinojo_banner_campaign_items i
  join public.kinojo_banner_campaigns c on c.campaign_id=i.campaign_id
  where c.event_group_id=p_event_group_id and i.asset_id=p_asset_id;

  if v_kind is null then
    return jsonb_build_object('ok',false,'code','BANNER_COMPOSITE_TARGET_NOT_FOUND');
  end if;
  if v_hash_count<>1 then
    return jsonb_build_object('ok',false,'code','BANNER_COMPOSITE_LAYER_MISMATCH');
  end if;
  if (v_kind='MAIN' and (p_width<>1536 or p_height<>864))
     or (v_kind='SIDE' and (p_width<>300 or p_height<>715)) then
    return jsonb_build_object('ok',false,'code','BANNER_COMPOSITE_DIMENSIONS_INVALID');
  end if;

  update public.kinojo_banner_campaign_items i
     set composite_object_path=p_object_path,
         composite_mime_type=lower(p_mime_type),
         composite_size_bytes=p_size_bytes,
         composite_width=p_width,
         composite_height=p_height,
         composite_source_hash=v_hash,
         updated_at=clock_timestamp()
    from public.kinojo_banner_campaigns c
   where c.campaign_id=i.campaign_id
     and c.event_group_id=p_event_group_id
     and i.asset_id=p_asset_id;
  get diagnostics v_updated=row_count;

  return jsonb_build_object(
    'ok',true,'apiVersion','396','contract','banner-composite-register-v396',
    'eventGroupId',p_event_group_id,'assetId',p_asset_id,
    'attachedItemCount',v_updated,'sourceHash',v_hash
  );
exception
  when check_violation then
    return jsonb_build_object('ok',false,'code','BANNER_COMPOSITE_INVALID');
end;
$function$;

