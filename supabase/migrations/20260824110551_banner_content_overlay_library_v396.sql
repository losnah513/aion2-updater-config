create or replace function private.kinojo_banner_content_from_item_v396(
  p_item jsonb,
  p_previous jsonb default '[]'::jsonb
) returns jsonb
language plpgsql
immutable
set search_path = pg_catalog, private
as $function$
declare
  v_layers jsonb;
begin
  if p_item ? 'contentOverlays' then
    return private.kinojo_banner_content_overlays_normalize_v396(p_item->'contentOverlays');
  end if;
  if p_item ? 'textOverlays' then
    if jsonb_typeof(p_item->'textOverlays')<>'array' then
      raise exception using errcode='P0001',message='BANNER_CONTENT_LAYERS_INVALID';
    end if;
    select coalesce(jsonb_agg(value || jsonb_build_object('type','TEXT')),'[]'::jsonb)
      into v_layers from jsonb_array_elements(p_item->'textOverlays');
    return private.kinojo_banner_content_overlays_normalize_v396(v_layers);
  end if;
  if p_item ? 'textOverlay' then
    return private.kinojo_banner_content_overlays_normalize_v396(
      jsonb_build_array(p_item->'textOverlay' || jsonb_build_object('type','TEXT','layerPosition','FRONT'))
    );
  end if;
  return private.kinojo_banner_content_overlays_normalize_v396(p_previous);
end;
$function$;

create or replace function private.kinojo_banner_content_legacy_overlay_v396(
  p_value jsonb
) returns jsonb
language plpgsql
immutable
set search_path = pg_catalog, private
as $function$
declare
  v_layer jsonb;
begin
  for v_layer in
    select value from jsonb_array_elements(
      private.kinojo_banner_content_overlays_normalize_v396(p_value)
    )
  loop
    if v_layer->>'type'='TEXT' and v_layer->>'layerPosition'='FRONT'
       and coalesce((v_layer->>'enabled')::boolean,false)
       and char_length(btrim(coalesce(v_layer->>'text','')))>0 then
      return private.kinojo_banner_text_overlay_normalize_v394(
        v_layer - 'type' - 'layerPosition' - 'horizontalPosition'
          - 'opacity' - 'sizePercent' - 'rotationDeg'
      );
    end if;
  end loop;
  return private.kinojo_banner_text_overlay_normalize_v394(null);
end;
$function$;

