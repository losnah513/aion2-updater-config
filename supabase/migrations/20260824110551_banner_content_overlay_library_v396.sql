create or replace function public.kinojo_banner_event_save_v396(
  p_session_token text,
  p_event_group_id uuid,
  p_payload jsonb
) returns jsonb
language plpgsql
security definer
set search_path = pg_catalog, public, private
as $function$
declare
  v_gate jsonb;
  v_result jsonb;
  v_group_id uuid;
  v_variants jsonb := p_payload->'variants';
  v_variant jsonb;
  v_items jsonb;
  v_item jsonb;
  v_page text;
  v_role text;
  v_campaign_id bigint;
  v_asset_id bigint;
  v_content_key text;
  v_content jsonb;
  v_previous_content jsonb := '{}'::jsonb;
begin
  v_gate := private.kinojo_banner_require_master_v384(p_session_token);
  if coalesce((v_gate->>'ok')::boolean,false) is not true then return v_gate; end if;

  if p_event_group_id is not null then
    select coalesce(jsonb_object_agg(
      c.page_code||':'||c.event_role||':'||i.asset_id::text,
      i.content_overlays
    ),'{}'::jsonb) into v_previous_content
    from public.kinojo_banner_campaigns c
    join public.kinojo_banner_campaign_items i on i.campaign_id=c.campaign_id
    where c.event_group_id=p_event_group_id;
  end if;

  if jsonb_typeof(v_variants)='array' then
    for v_variant in select value from jsonb_array_elements(v_variants)
    loop
      v_items := v_variant->'items';
      if jsonb_typeof(v_variant)='object' and jsonb_typeof(v_items)='array' then
        for v_item in select value from jsonb_array_elements(v_items)
        loop
          perform private.kinojo_banner_content_from_item_v396(v_item,'[]'::jsonb);
        end loop;
      end if;
    end loop;
  end if;

  v_result := public.kinojo_banner_event_save_v394(
    p_session_token,p_event_group_id,p_payload
  );
  if coalesce((v_result->>'ok')::boolean,false) is not true then return v_result; end if;
  v_group_id := (v_result->>'eventGroupId')::uuid;

  if jsonb_typeof(v_variants)='array' then
    for v_variant in select value from jsonb_array_elements(v_variants)
    loop
      if jsonb_typeof(v_variant)='object' then
        v_page := upper(btrim(coalesce(v_variant->>'pageCode','')));
        v_role := upper(btrim(coalesce(v_variant->>'eventRole','')));
        select c.campaign_id into v_campaign_id
        from public.kinojo_banner_campaigns c
        where c.event_group_id=v_group_id
          and c.page_code=v_page
          and c.event_role=v_role;
        if not found then
          raise exception using errcode='P0001',message='BANNER_EVENT_CAMPAIGN_NOT_FOUND';
        end if;

        v_items := v_variant->'items';
        if jsonb_typeof(v_items)='array' then
          for v_item in select value from jsonb_array_elements(v_items)
          loop
            begin
              v_asset_id := (v_item->>'assetId')::bigint;
            exception when others then
              raise exception using errcode='P0001',message='BANNER_CAMPAIGN_ASSET_ID_INVALID';
            end;
            v_content_key := v_page||':'||v_role||':'||v_asset_id::text;
            v_content := private.kinojo_banner_content_from_item_v396(
              v_item,
              case when v_previous_content ? v_content_key
                then v_previous_content->v_content_key else '[]'::jsonb end
            );
            update public.kinojo_banner_campaign_items
               set composite_object_path=case when content_overlays is distinct from v_content then null else composite_object_path end,
                   composite_mime_type=case when content_overlays is distinct from v_content then null else composite_mime_type end,
                   composite_size_bytes=case when content_overlays is distinct from v_content then null else composite_size_bytes end,
                   composite_width=case when content_overlays is distinct from v_content then null else composite_width end,
                   composite_height=case when content_overlays is distinct from v_content then null else composite_height end,
                   composite_source_hash=case when content_overlays is distinct from v_content then null else composite_source_hash end,
                   content_overlays=v_content,
                   text_overlay=private.kinojo_banner_content_legacy_overlay_v396(v_content),
                   updated_at=clock_timestamp()
             where campaign_id=v_campaign_id and asset_id=v_asset_id;
            if not found then
              raise exception using errcode='P0001',message='BANNER_EVENT_ITEM_NOT_FOUND';
            end if;
          end loop;
        end if;
      end if;
    end loop;
  end if;

  update private.kinojo_banner_event_groups_v391
     set updated_by_member_id=(v_gate->>'memberId')::bigint,
         updated_at=clock_timestamp()
   where event_group_id=v_group_id;

  return jsonb_build_object(
    'ok',true,'apiVersion','396','contract','banner-event-save-v396',
    'eventGroupId',v_group_id,
    'savedCampaignIds',coalesce(v_result->'savedCampaignIds','[]'::jsonb),
    'event',private.kinojo_banner_event_json_v396(v_group_id)
  );
exception
  when sqlstate 'P0001' then
    return jsonb_build_object('ok',false,'code',coalesce(nullif(sqlerrm,''),'BANNER_EVENT_SAVE_FAILED'));
end;
$function$;

create or replace function public.kinojo_banner_event_publish_v396(
  p_session_token text,
  p_event_group_id uuid
) returns jsonb
language plpgsql
security definer
set search_path = pg_catalog, public, private
as $function$
declare
  v_gate jsonb;
  v_result jsonb;
  v_item record;
  v_layer jsonb;
  v_asset_id bigint;
  v_expected_hash text;
begin
  v_gate := private.kinojo_banner_require_master_v384(p_session_token);
  if coalesce((v_gate->>'ok')::boolean,false) is not true then return v_gate; end if;

  for v_item in
    select i.item_id,i.content_overlays
    from public.kinojo_banner_campaign_items i
    join public.kinojo_banner_campaigns c on c.campaign_id=i.campaign_id
    where c.event_group_id=p_event_group_id and i.is_enabled
  loop
    v_expected_hash := md5(
      private.kinojo_banner_content_overlays_normalize_v396(v_item.content_overlays)::text
    );
    for v_layer in
      select value from jsonb_array_elements(
        private.kinojo_banner_content_overlays_normalize_v396(v_item.content_overlays)
      )
    loop
      if coalesce((v_layer->>'enabled')::boolean,false) then
        if v_layer->>'type'='TEXT' and char_length(btrim(coalesce(v_layer->>'text','')))=0 then
          return jsonb_build_object('ok',false,'code','BANNER_CONTENT_TEXT_REQUIRED','itemId',v_item.item_id);
        elsif v_layer->>'type'='EMOJI' and char_length(btrim(coalesce(v_layer->>'emoji','')))=0 then
          return jsonb_build_object('ok',false,'code','BANNER_CONTENT_EMOJI_REQUIRED','itemId',v_item.item_id);
        elsif v_layer->>'type' in ('EMOTICON','STICKER','BADGE') then
          begin
            v_asset_id := (v_layer->>'overlayAssetId')::bigint;
          exception when others then
            return jsonb_build_object('ok',false,'code','BANNER_CONTENT_ASSET_REQUIRED','itemId',v_item.item_id);
          end;
          if not exists (
            select 1 from public.kinojo_banner_overlay_assets a
            where a.overlay_asset_id=v_asset_id
              and a.status='READY'
              and a.asset_kind=v_layer->>'type'
          ) then
            return jsonb_build_object('ok',false,'code','BANNER_CONTENT_ASSET_REQUIRED','itemId',v_item.item_id);
          end if;
        end if;
      end if;
    end loop;
    if private.kinojo_banner_content_enabled_v396(v_item.content_overlays) and not exists (
      select 1
      from public.kinojo_banner_campaign_items check_item
      where check_item.item_id=v_item.item_id
        and check_item.composite_object_path is not null
        and check_item.composite_source_hash=v_expected_hash
    ) then
      return jsonb_build_object(
        'ok',false,'code','BANNER_COMPOSITE_REQUIRED','itemId',v_item.item_id
      );
    end if;
  end loop;

  v_result := public.kinojo_banner_event_publish_v394(
    p_session_token,p_event_group_id
  );
  if coalesce((v_result->>'ok')::boolean,false) is not true then return v_result; end if;
  return jsonb_build_object(
    'ok',true,'apiVersion','396','contract','banner-event-publish-v396',
    'eventGroupId',p_event_group_id,
    'publishedCampaignCount',v_result->'publishedCampaignCount',
    'event',private.kinojo_banner_event_json_v396(p_event_group_id)
  );
exception
  when invalid_text_representation or numeric_value_out_of_range then
    return jsonb_build_object('ok',false,'code','BANNER_CONTENT_ASSET_REQUIRED');
end;
$function$;

create or replace function private.kinojo_banner_content_manifest_v396(
  p_value jsonb
) returns jsonb
language plpgsql
stable
security definer
set search_path = pg_catalog, public, private
as $function$
declare
  v_result jsonb := '[]'::jsonb;
  v_layer jsonb;
  v_asset public.kinojo_banner_overlay_assets;
begin
  for v_layer in
    select value from jsonb_array_elements(
      private.kinojo_banner_content_overlays_normalize_v396(p_value)
    )
  loop
    if not coalesce((v_layer->>'enabled')::boolean,false) then continue; end if;
    if v_layer->>'type'='TEXT' and char_length(btrim(coalesce(v_layer->>'text','')))=0 then continue; end if;
    if v_layer->>'type'='EMOJI' and char_length(btrim(coalesce(v_layer->>'emoji','')))=0 then continue; end if;
    if v_layer->>'type' in ('EMOTICON','STICKER','BADGE') then
      select a.* into v_asset
      from public.kinojo_banner_overlay_assets a
      where a.overlay_asset_id=(v_layer->>'overlayAssetId')::bigint
        and a.status='READY'
        and a.asset_kind=v_layer->>'type';
      if not found then continue; end if;
      v_layer := (v_layer - 'overlayAssetId') || jsonb_build_object(
        'sourceType','STORAGE','objectPath',v_asset.object_path,
        'mimeType',v_asset.mime_type,'width',v_asset.width,'height',v_asset.height,
        'assetKind',v_asset.asset_kind
      );
    end if;
    v_result := v_result || jsonb_build_array(v_layer);
  end loop;
  return v_result;
exception when invalid_text_representation or numeric_value_out_of_range then
  return v_result;
end;
$function$;

create or replace function private.kinojo_banner_manifest_internal_v396(
  p_page_code text,
  p_slot_code text,
  p_now timestamptz
) returns jsonb
language plpgsql
stable
security definer
set search_path = pg_catalog, public, private
as $function$
declare
  v_base jsonb;
  v_playlist jsonb := '[]'::jsonb;
  v_manifest_version text;
begin
  v_base := private.kinojo_banner_manifest_internal_v395(
    p_page_code,p_slot_code,p_now
  );
  if coalesce((v_base->>'ok')::boolean,false) is not true then return v_base; end if;

  select coalesce(jsonb_agg(
    p.item || case
      when private.kinojo_banner_content_enabled_v396(i.content_overlays)
       and i.composite_object_path is not null
       and i.composite_source_hash=md5(
         private.kinojo_banner_content_overlays_normalize_v396(i.content_overlays)::text
       ) then jsonb_build_object(
         'sourceType','STORAGE','staticPath',null,
         'objectPath',i.composite_object_path,
         'fitMode','COVER','composite',true,
         'textOverlay',private.kinojo_banner_text_overlay_normalize_v394(null),
         'contentOverlays','[]'::jsonb
       )
      else jsonb_build_object(
        'composite',false,
        'contentOverlays',private.kinojo_banner_content_manifest_v396(i.content_overlays)
      )
    end order by p.ordinality
  ),'[]'::jsonb) into v_playlist
  from jsonb_array_elements(coalesce(v_base->'playlist','[]'::jsonb))
    with ordinality p(item,ordinality)
  join public.kinojo_banner_campaign_items i
    on i.item_id=(p.item->>'itemId')::bigint;

  v_manifest_version := 'bm396-'||substr(md5(
    coalesce(v_base->>'manifestVersion','')||'|'||v_playlist::text
  ),1,24);
  return v_base || jsonb_build_object(
    'apiVersion','396','contract','banner-manifest-internal-v396',
    'manifestVersion',v_manifest_version,'playlist',v_playlist
  );
end;
$function$;

