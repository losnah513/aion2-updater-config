-- Banner redesign stage 5: reusable overlay library, general content layers,
-- draft save/publish round-trip, and public manifest delivery. Text layers
-- remain limited to three; reusable emoji/image decoration layers are limited
-- to three more per banner image.

create table if not exists public.kinojo_banner_overlay_assets (
  overlay_asset_id bigint generated by default as identity primary key,
  asset_kind text not null,
  display_name text not null,
  object_path text not null unique,
  mime_type text not null,
  size_bytes bigint not null,
  width integer not null,
  height integer not null,
  status text not null default 'READY',
  created_by_member_id bigint not null,
  created_at timestamptz not null default clock_timestamp(),
  updated_at timestamptz not null default clock_timestamp(),
  constraint kinojo_banner_overlay_asset_kind_v396_chk
    check (asset_kind in ('EMOTICON','STICKER','BADGE')),
  constraint kinojo_banner_overlay_asset_name_v396_chk
    check (char_length(btrim(display_name)) between 1 and 80),
  constraint kinojo_banner_overlay_asset_path_v396_chk
    check (object_path ~ '^[0-9]{4}/[0-9]{2}/[0-9a-f-]{36}\.(jpg|jpeg|png|webp)$'),
  constraint kinojo_banner_overlay_asset_mime_v396_chk
    check (mime_type in ('image/jpeg','image/png','image/webp')),
  constraint kinojo_banner_overlay_asset_size_v396_chk
    check (size_bytes between 1 and 5242880),
  constraint kinojo_banner_overlay_asset_dimensions_v396_chk
    check (width between 1 and 4096 and height between 1 and 4096),
  constraint kinojo_banner_overlay_asset_status_v396_chk
    check (status in ('READY','ARCHIVED'))
);

