create or replace function private.kinojo_banner_auto_playlist_v407(
  p_page_code text,
  p_slot_code text,
  p_now timestamptz
) returns jsonb
language sql
stable
security definer
set search_path=pg_catalog,public,private
as $function$
  with pools as (
    select p.*,
      pg_catalog.floor(extract(epoch from p_now)/300.0)::bigint bucket
    from public.kinojo_banner_auto_pools_v407 p
    where p.is_enabled
      and pg_catalog.upper(pg_catalog.btrim(p_page_code))=any(p.target_pages)
      and pg_catalog.upper(pg_catalog.btrim(p_slot_code))=any(p.slot_codes)
      and (p.starts_at is null or p.starts_at<=p_now)
      and (p.ends_at is null or p.ends_at>p_now)
  ), scored as (
    select p.pool_id,p.priority,p.updated_at,p.bucket,p.show_character_name,
      p.slide_interval_ms,p.transition_duration_ms,p.transition_effect,p.transition_direction,
      e.asset_id,e.character_id,e.character_name,e.sort_order,
      a.source_type,a.static_path,a.object_path,a.default_alt,
      pc.object_path composite_object_path,
      pg_catalog.row_number() over(partition by p.pool_id order by
        pg_catalog.md5(p.bucket::text||'|'||p.pool_id::text||'|'||p_page_code||'|'||p_slot_code||'|'||e.asset_id::text),e.asset_id) current_rank,
      pg_catalog.row_number() over(partition by p.pool_id order by
        pg_catalog.md5((p.bucket-1)::text||'|'||p.pool_id::text||'|'||p_page_code||'|'||p_slot_code||'|'||e.asset_id::text) desc,e.asset_id desc) previous_reverse_rank,
      pg_catalog.count(*) over(partition by p.pool_id) pool_count
    from pools p
    join private.kinojo_banner_auto_pool_candidates_v407(p.pool_id) e on true
    join public.kinojo_banner_assets a on a.asset_id=e.asset_id
    left join public.kinojo_banner_auto_pool_composites_v407 pc
      on pc.pool_id=p.pool_id and pc.asset_id=e.asset_id
      and pc.source_hash=private.kinojo_banner_auto_pool_source_hash_v407(p.pool_id,e.asset_id)
    where not p.show_character_name or pc.object_path is not null
  ), flags as (
    select s.*,
      pg_catalog.max(asset_id) filter(where current_rank=1) over(partition by pool_id)
        =pg_catalog.max(asset_id) filter(where previous_reverse_rank=1) over(partition by pool_id) repeat_boundary
    from scored s
  ), ordered as (
    select f.*,
      case when repeat_boundary and pool_count>1 and current_rank=1 then 2
           when repeat_boundary and pool_count>1 and current_rank=2 then 1
           else current_rank end playback_rank
    from flags f
  )
  select coalesce(pg_catalog.jsonb_agg(pg_catalog.jsonb_build_object(
    'sourceType',case when o.show_character_name then 'STORAGE' else o.source_type end,
    'staticPath',case when o.show_character_name then null else o.static_path end,
    'objectPath',case when o.show_character_name then o.composite_object_path else o.object_path end,
    'alt',coalesce(nullif(o.default_alt,''),o.character_name,''),
    'clickUrl',null,'fitMode','COVER',
    'slideIntervalMs',o.slide_interval_ms,
    'transitionDurationMs',o.transition_duration_ms,
    'transitionEffect',o.transition_effect,'transitionDirection',o.transition_direction,
    'textOverlay',pg_catalog.jsonb_build_object('enabled',false),
    'sourceMode','AUTO_LIBRARY_POOL','characterName',o.character_name
  ) order by o.priority desc,o.updated_at,o.pool_id,o.playback_rank),'[]'::jsonb)
  from ordered o
$function$;

